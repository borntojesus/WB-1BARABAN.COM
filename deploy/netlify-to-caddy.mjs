#!/usr/bin/env node
// Convert Netlify redirect rules into a Caddy snippet for the homelab staging.
//
//   node deploy/netlify-to-caddy.mjs <dist>/_redirects [netlify.toml ...] > redirects.caddy
//
// Sources are read in the order given (Netlify reads _redirects before netlify.toml),
// and the first matching rule wins, as on Netlify. Supported: literal paths (with or
// without a trailing slash), `*` splats, `:placeholder` segments, query conditions
// (`key=value`, `key=:var`), status 301/302/303/307/308, 200 rewrites to a local path,
// 404/410 with a local page, and force (`!` / `force = true`). A rule that is not forced
// only applies when no file exists at the path, as on Netlify. Skipped (listed as
// comments): host-qualified `from`, proxies to another origin, Country/Language/Role
// conditions. The snippet is a single `route` block, imported inside a site block.
import fs from "node:fs";

const files = process.argv.slice(2);
if (!files.length) {
  console.error("usage: netlify-to-caddy.mjs <_redirects|netlify.toml> ...");
  process.exit(2);
}

const rules = [];
for (const f of files) {
  if (!fs.existsSync(f)) continue;
  const text = fs.readFileSync(f, "utf8");
  if (f.endsWith(".toml")) rules.push(...parseToml(text, f));
  else rules.push(...parseRedirects(text, f));
}

function parseRedirects(text, src) {
  const out = [];
  text.split("\n").forEach((raw, i) => {
    const line = raw.replace(/\s+#.*$/, "").trim();
    if (!line || line.startsWith("#")) return;
    const t = line.split(/\s+/);
    const from = t.shift();
    const query = {};
    while (t.length && !/^(\/|https?:)/.test(t[0]) && t[0].includes("=")) {
      const [k, ...v] = t.shift().split("=");
      query[k] = v.join("=");
    }
    const to = t.shift();
    let status = 301;
    let force = false;
    if (t.length && /^\d{3}!?$/.test(t[0])) {
      const s = t.shift();
      force = s.endsWith("!");
      status = parseInt(s, 10);
    }
    const conditions = t.length ? t.join(" ") : "";
    out.push({
      from,
      to,
      status,
      force,
      query,
      conditions,
      src: `${src}:${i + 1}`,
    });
  });
  return out;
}

function parseToml(text, src) {
  const out = [];
  const blocks = text.split(/^\s*\[\[redirects\]\]\s*$/m).slice(1);
  for (const b of blocks) {
    const body = b.split(/^\s*\[/m)[0];
    const get = (k) => {
      const m = body.match(new RegExp(`^\\s*${k}\\s*=\\s*(.+?)\\s*$`, "m"));
      if (!m) return undefined;
      const v = m[1].replace(/\s+#.*$/, "");
      if (/^".*"$/.test(v) || /^'.*'$/.test(v)) return v.slice(1, -1);
      if (v === "true" || v === "false") return v === "true";
      if (/^\d+$/.test(v)) return parseInt(v, 10);
      return v;
    };
    const query = {};
    const q = get("query");
    if (typeof q === "string" && q.startsWith("{")) {
      for (const m of q.matchAll(/(\w+)\s*=\s*"([^"]*)"/g)) query[m[1]] = m[2];
    }
    const cond = get("conditions");
    out.push({
      from: get("from"),
      to: get("to"),
      status: get("status") ?? 301,
      force: get("force") === true,
      query,
      conditions: cond ? String(cond) : "",
      src: `${src}[[redirects]]`,
    });
  }
  return out;
}

const esc = (s) => `"${String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
const reEsc = (s) => s.replace(/[.+?^${}()|[\]\\]/g, "\\$&");

const lines = [
  "# Generated by deploy/netlify-to-caddy.mjs from the Netlify rules of this build. Do not edit.",
  "route {",
];
let n = 0;
let skipped = 0;

for (const r of rules) {
  const why =
    !r.from || !r.to
      ? "incomplete rule"
      : /^https?:/.test(r.from)
        ? "host-qualified from"
        : r.conditions
          ? `conditions ${r.conditions}`
          : r.status === 200 && /^https?:/.test(r.to)
            ? "proxy to another origin"
            : ![200, 301, 302, 303, 307, 308, 404, 410].includes(r.status)
              ? `status ${r.status}`
              : "";
  if (why) {
    lines.push(
      `\t# skipped (${why}): ${r.from} ${r.to} ${r.status}`.replace(/\n/g, " "),
    );
    skipped++;
    continue;
  }
  n++;
  const name = `r${n}`;
  let [path, qs] = r.from.split("?");
  const query = { ...r.query };
  if (qs)
    for (const kv of qs.split("&")) {
      const [k, ...v] = kv.split("=");
      query[k] = v.join("=");
    }

  const vars = {}; // netlify name -> caddy placeholder
  const segs = path.split("/");
  const dynamic = segs.some((s) => s.startsWith(":")) || path.includes("*");
  const m = [];
  if (dynamic) {
    let idx = 0;
    let re = "";
    segs.forEach((s, i) => {
      if (i === 0) return;
      if (s === "*" && i === segs.length - 1) {
        idx++;
        vars.splat = `{re.${name}.${idx}}`;
        re += "(?:/(.*))?";
      } else if (s.startsWith(":")) {
        idx++;
        vars[s.slice(1)] = `{re.${name}.${idx}}`;
        re += "/([^/]+)";
      } else if (s.includes("*")) {
        idx++;
        vars.splat = `{re.${name}.${idx}}`;
        re += "/" + s.split("*").map(reEsc).join("(.*)");
      } else {
        re += "/" + reEsc(s);
      }
    });
    if (!path.endsWith("*")) re += "/?";
    m.push(`path_regexp ${name} ${esc(`(?i)^${re || "/"}$`)}`);
  } else {
    const base = path.length > 1 ? path.replace(/\/$/, "") : path;
    const alts = base === "/" ? ["/"] : [base, base + "/"];
    m.push(`path ${alts.map(esc).join(" ")}`);
  }
  for (const [k, v] of Object.entries(query)) {
    if (v.startsWith(":")) {
      m.push(`query ${esc(`${k}=*`)}`);
      vars[v.slice(1)] = `{query.${k}}`;
    } else {
      m.push(`query ${esc(`${k}=${v}`)}`);
    }
  }
  if (!r.force) m.push("not file {path} {path}/index.html {path}.html");

  let to = r.to;
  for (const [k, ph] of Object.entries(vars)) to = to.split(`:${k}`).join(ph);

  lines.push(`\t# ${r.src}`);
  lines.push(`\t@${name} {`);
  for (const x of m) lines.push(`\t\t${x}`);
  lines.push("\t}");
  if (r.status >= 300 && r.status < 400) {
    lines.push(`\tredir @${name} ${esc(to)} ${r.status}`);
  } else if (r.status === 200) {
    lines.push(`\trewrite @${name} ${esc(to)}`);
  } else {
    lines.push(`\thandle @${name} {`);
    lines.push(`\t\trewrite * ${esc(to)}`);
    lines.push(`\t\tfile_server {`);
    lines.push(`\t\t\tstatus ${r.status}`);
    lines.push("\t\t}");
    lines.push("\t}");
  }
}
lines.push("}");
process.stdout.write(lines.join("\n") + "\n");
console.error(`netlify-to-caddy: ${n} rules, ${skipped} skipped`);
